const fs=require('fs'); const L=require(require.resolve('lucide-react',{paths:[process.cwd()]}));
const names=JSON.parse(fs.readFileSync(process.argv[2]));
const pas=n=>n.split('-').map(p=>p[0].toUpperCase()+p.slice(1)).join('');
const src=fs.readdirSync('components').filter(f=>f.endsWith('.jsx')).map(f=>fs.readFileSync('components/'+f,'utf8')).join('\n');
// only names that are used in an icon position
const used=new Set();
for(const m of src.matchAll(/(?:icon|iconRight|name|ico)\s*[:=]\s*\{?\s*(?:[\w.]+\s*\?\s*)?["']([a-z0-9-]+)["'](?:\s*:\s*["']([a-z0-9-]+)["'])?/g)){ used.add(m[1]); if(m[2]) used.add(m[2]); }
for(const m of src.matchAll(/<Icon[^>]*name=\{[^}]*?["']([a-z0-9-]+)["'][^}]*?(?:["']([a-z0-9-]+)["'])?/g)){ used.add(m[1]); if(m[2]) used.add(m[2]); }
const ok=[],miss=[];
for(const n of [...used].sort()){ if(L[pas(n)]) ok.push(n); else miss.push(n); }
// fallback: any other kebab literal that is a lucide icon AND appears in an array/object of icon-ish data
const extra=names.filter(n=>!used.has(n)&&L[pas(n)]&&/-/.test(n));
const all=[...new Set([...ok,...extra])].sort();
let out='/* Generated by scripts/gen-icons: the lucide icons the site uses, by name.\n   Add an icon here when a component asks for a new name. */\nimport {\n'+all.map(n=>'  '+pas(n)+',').join('\n')+'\n} from "lucide-react";\n\nexport const ICONS = {\n'+all.map(n=>'  "'+n+'": '+pas(n)+',').join('\n')+'\n};\n';
fs.writeFileSync('components/icons.js',out);
console.log('icons',all.length,'missing',miss.join(','),'| extra',extra.join(','));
